"""Generate rec_step_gen.hip: the parametric recurrence-step benchmark with every count a compile-time constant
(one template instance per configuration line of rec_step_cfg.txt), so each step compiles to straight-line code like
the production kernels (the runtime-count version carried ~1 us of loop / scratch overhead per step).
    python3 rec_step_gen.py rec_step_cfg.txt > rec_step_gen.hip
Config columns (per wave per step): tag W cp n1 i1 n2 i2 nv1 nv2 nw1 nw2 nr nld nst bar pf hbm"""
import sys

HEAD = r'''// GENERATED by rec_step_gen.py -- parametric recurrence step, compile-time counts (see rec_step_gen.py)
#include <hip/hip_runtime.h>
#include <cstdio>
typedef short v4bh __attribute__((ext_vector_type(4)));
typedef float f4 __attribute__((ext_vector_type(4)));
typedef unsigned u2 __attribute__((ext_vector_type(2)));
__device__ __forceinline__ f4 mm(v4bh a, v4bh b, f4 c) { return __builtin_amdgcn_mmac_f32_16x16x16bf16(a, b, c); }

template <int W, int N1, int N2, int G, int NV1, int NV2, int NW1, int NW2, int NR, int NLD, int NST, int BAR, int PF>
__global__ void __launch_bounds__(64 * W) k_step(int NT, const char* __restrict__ g, char* __restrict__ gs, size_t gmask,
                                                 float* out) {
    __shared__ __align__(16) unsigned char lds[16384];
    const int tid = threadIdx.x, l = tid & 63, w = tid >> 6;
    const unsigned lbase = (unsigned)(uintptr_t)lds + (unsigned)(w * 1024 + l * 8);
    const unsigned rbase = (unsigned)(uintptr_t)lds + (unsigned)(((w + 1) % W) * 1024 + l * 8);
    v4bh a = v4bh{(short)(0x3c00 + l), 0x3c00, 0x3c01, 0x3c02};
    f4 acc[G];
    #pragma unroll
    for (int i = 0; i < G; ++i) acc[i] = f4{0.f, 0.f, 0.f, (float)i};
    float x0 = 1.f, x1 = 2.f, x2 = 3.f;
    constexpr int NL = NLD > 0 ? NLD : 1;
    u2 ldv[NL];
    #pragma unroll
    for (int i = 0; i < NL; ++i) ldv[i] = u2{0u, 0u};
    const size_t cta_off = ((size_t)blockIdx.x * 8191u * 65536u) & gmask;
    constexpr size_t STEPB = (size_t)(NLD * 512 * W + 4096);
    for (int s = 0; s < NT; ++s) {
        const size_t soff = (cta_off + (size_t)s * STEPB) & gmask;
        const char* gp = g + soff + (size_t)(w * NLD) * 512 + l * 8;
        if (PF) asm volatile("s_waitcnt vmcnt(0)" ::: "memory");
        unsigned use = 0;
        #pragma unroll
        for (int i = 0; i < NLD; ++i) use ^= ldv[i].x ^ ldv[i].y;
        #pragma unroll
        for (int i = 0; i < NLD; ++i) ldv[i] = *reinterpret_cast<const u2*>(gp + (size_t)i * 512);
        if (!PF && NLD) { asm volatile("s_waitcnt vmcnt(0)" ::: "memory");
            #pragma unroll
            for (int i = 0; i < NLD; ++i) use ^= ldv[i].x; }
        a[0] = (short)(a[0] ^ (short)(use & 1));
        #pragma unroll
        for (int j = 0; j < N1; ++j) acc[j % G] = mm(a, a, acc[j % G]);
        float y = acc[0][0] + acc[G - 1][1];
        #pragma unroll
        for (int i = 0; i < NV1; ++i) {
            if ((i & 3) == 0) asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(y) : "v"(x0));
            else if ((i & 3) == 1) asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(x0) : "v"(y));
            else if ((i & 3) == 2) asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(x1) : "v"(y));
            else asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(x2) : "v"(y));
        }
        const unsigned wv = __float_as_uint(y + x0 + x1 + x2);
        #pragma unroll
        for (int i = 0; i < NW1; ++i) { u2 v = {wv, (unsigned)i}; asm volatile("ds_write_b64 %0, %1" :: "v"(lbase + (unsigned)(i & 7) * 4096u / 8u * 0u + (unsigned)(i & 1) * 8192u), "v"(v)); }
        if (NW1) asm volatile("s_waitcnt lgkmcnt(0)" ::: "memory");
        if (BAR >= 1) asm volatile("s_barrier" ::: "memory");
        unsigned rd = 0;
        #pragma unroll
        for (int i = 0; i < NR; ++i) { u2 v; asm volatile("ds_read_b64 %0, %1" : "=v"(v) : "v"(rbase + (unsigned)(i & 1) * 8192u)); rd ^= v.x; }
        if (NR) asm volatile("s_waitcnt lgkmcnt(0)" ::: "memory");
        v4bh b = a;
        b[1] = (short)(b[1] ^ (short)(rd & 1));
        #pragma unroll
        for (int j = 0; j < N2; ++j) acc[j % G] = mm(b, a, acc[j % G]);
        float z = acc[0][2];
        #pragma unroll
        for (int i = 0; i < NV2; ++i) {
            if ((i & 3) == 0) asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(z) : "v"(x0));
            else if ((i & 3) == 1) asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(x0) : "v"(z));
            else if ((i & 3) == 2) asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(x1) : "v"(z));
            else asm volatile("v_fma_f32 %0, %0, %1, 1.0" : "+v"(x2) : "v"(z));
        }
        const unsigned zv = __float_as_uint(z + x1);
        #pragma unroll
        for (int i = 0; i < NW2; ++i) { u2 v = {zv, (unsigned)i}; asm volatile("ds_write_b64 %0, %1" :: "v"(lbase + 4096u + (unsigned)(i & 1) * 8192u), "v"(v)); }
        if (NW2) asm volatile("s_waitcnt lgkmcnt(0)" ::: "memory");
        if (BAR >= 2) asm volatile("s_barrier" ::: "memory");
        char* sp = gs + soff + (size_t)(w * NST) * 512 + l * 8;
        #pragma unroll
        for (int i = 0; i < NST; ++i) *reinterpret_cast<u2*>(sp + (size_t)i * 512) = u2{zv, (unsigned)i};
        a[2] = (short)(a[2] ^ (short)(zv & 1));
    }
    float s = x0 + x1 + x2;
    #pragma unroll
    for (int i = 0; i < G; ++i) s += acc[i][0];
    if (s == 1.2345f) out[blockIdx.x * 64 * W + tid] = s;
}

typedef void (*KF)(int, const char*, char*, size_t, float*);
struct Ent { const char* tag; int W, cp, hbm; KF f; const char* desc; };
'''

TAIL = r'''
int main() {
    const size_t big = (size_t)1 << 30;
    char *g, *gs; float* out;
    hipMalloc(&g, big + (1 << 22)); hipMalloc(&gs, big + (1 << 22)); hipMalloc(&out, 80 * 3 * 512 * 4);
    hipMemset(g, 0, big + (1 << 22));
    hipEvent_t e0, e1; hipEventCreate(&e0); hipEventCreate(&e1);
    printf("# clk 1.50 GHz; us per step (80 x cp CTAs, each its own chain); counts per wave per step\n");
    for (const Ent& e : ENTS) {
        const size_t gmask = (e.hbm ? big : ((size_t)4 << 20)) - 1;
        const int NT = 1024;
        hipLaunchKernelGGL(e.f, dim3(80 * e.cp), dim3(64 * e.W), 0, 0, 16, g, gs, gmask, out);
        hipDeviceSynchronize();
        float best = 1e30f;
        for (int r = 0; r < 3; ++r) {
            hipEventRecord(e0);
            hipLaunchKernelGGL(e.f, dim3(80 * e.cp), dim3(64 * e.W), 0, 0, NT, g, gs, gmask, out);
            hipEventRecord(e1); hipEventSynchronize(e1);
            float ms; hipEventElapsedTime(&ms, e0, e1); best = ms < best ? ms : best;
        }
        const double us = best * 1e3 / NT;
        printf("STEP %s %s us=%.4f cyc=%.0f\n", e.tag, e.desc, us, us * 1.5e3);
        fflush(stdout);
    }
    return 0;
}
'''


def main():
    cfgs = []
    for ln in open(sys.argv[1]):
        if ln.startswith("#") or len(ln.split()) < 17:
            continue
        t = ln.split()
        tag = t[0]
        W, cp, n1, i1, n2, i2, nv1, nv2, nw1, nw2, nr, nld, nst, bar, pf, hbm = map(int, t[1:17])
        cfgs.append((tag, W, cp, n1, max(1, i1), n2, nv1, nv2, nw1, nw2, nr, nld, nst, bar, pf, hbm))
    out = [HEAD, "static const Ent ENTS[] = {"]
    for (tag, W, cp, n1, G, n2, nv1, nv2, nw1, nw2, nr, nld, nst, bar, pf, hbm) in cfgs:
        desc = (f"W={W} cp={cp} n1={n1} G={G} n2={n2} nv1={nv1} nv2={nv2} nw1={nw1} nw2={nw2} nr={nr} nld={nld} "
                f"nst={nst} bar={bar} pf={pf} hbm={hbm}")
        out.append(f'    {{"{tag}", {W}, {cp}, {hbm}, k_step<{W}, {n1}, {n2}, {G}, {nv1}, {nv2}, {nw1}, {nw2}, {nr}, {nld}, '
                   f'{nst}, {bar}, {pf}>, "{desc}"}},')
    out.append("};")
    out.append(TAIL)
    print("\n".join(out))


if __name__ == "__main__":
    main()
